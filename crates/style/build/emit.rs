//! Writes the compiled grammar as static Rust tables.
use crate::{
    BuildError,
    compile::{BASE_TYPES, CompiledDescriptor, Grammar, Label, Node, UNBOUNDED},
    source::{Initial, Origin},
};
use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::Write,
};

const FUNCTION_SUFFIX: &str = "()";
const FUNCTION_VARIANT_SUFFIX: &str = "Fn";
const VENDOR_PREFIX: &str = "Dash";
const DIGIT_PREFIX: &str = "N";
/// Rust keywords that a CSS name can camel-case into.
const RESERVED: [&str; 1] = ["Self"];
const RESERVED_SUFFIX: &str = "Keyword";
const MAX_NODES: usize = u16::MAX as usize;
/// Data only the conformance tests read.
const TEST_ONLY: &str = "#[cfg(test)]";

pub(crate) fn emit(grammar: &Grammar) -> Result<String, BuildError> {
    if grammar.nodes.len() > MAX_NODES {
        return Err(BuildError::Invalid {
            context: "grammar".into(),
            message: format!("{} nodes exceed {MAX_NODES}", grammar.nodes.len()),
        });
    }
    let keywords = variants(grammar.keywords.iter().map(String::as_str), camel)?;
    let properties = variants(grammar.properties.iter().map(|p| p.name.as_str()), camel)?;
    let productions = variants(grammar.productions.keys().map(String::as_str), production)?;
    let descriptors = variants(
        grammar.descriptors.iter().map(descriptor_variant),
        str::to_owned,
    )?;
    let used_bases: BTreeSet<&str> = grammar
        .nodes
        .iter()
        .filter_map(|node| match node {
            Node::Base { name, .. } => Some(name.as_str()),
            _ => None,
        })
        .collect();
    if let Some(unused) = BASE_TYPES.iter().find(|base| !used_bases.contains(*base)) {
        return Err(BuildError::Invalid {
            context: "base types".into(),
            message: format!("<{unused}> is never referenced by the grammar"),
        });
    }
    let bases = variants(BASE_TYPES.iter().copied(), camel)?;

    let mut out = String::new();
    out.push_str("// @generated by crates/style/build from spec/css. Do not edit.\n\n");
    enumeration(&mut out, "Keyword", &keywords, true);
    enumeration(&mut out, "Property", &properties, true);
    enumeration(&mut out, "Production", &productions, false);
    enumeration(&mut out, "Descriptor", &descriptors, false);
    enumeration(&mut out, "Base", &bases, false);
    out.push_str("impl Production { pub(crate) fn root(self) -> NodeId { match self {\n");
    for (name, root) in &grammar.productions {
        writeln!(out, "Self::{} => {root},", productions[name]).unwrap();
    }
    out.push_str("} } }\n");

    let keyword = |name: &str| format!("Keyword::{}", keywords[name]);
    let property = |name: &str| format!("Property::{}", properties[name]);
    let label = |label: &Label| match label {
        Label::Property(name) => format!("Label::Property({})", property(name)),
        Label::Production(name) => {
            format!(
                "Label::Production(Production::{})",
                productions[name.as_str()]
            )
        }
    };

    writeln!(
        out,
        "pub(crate) static NODES: [Node; {}] = [",
        grammar.nodes.len()
    )
    .unwrap();
    for node in &grammar.nodes {
        let text = match node {
            Node::Keyword(name) => format!("Node::Keyword({})", keyword(name)),
            Node::Delim(c) => format!("Node::Delim({c:?})"),
            Node::Base { name, min, max } => format!(
                "Node::Base(Base::{}, Range {{ min: {}, max: {} }})",
                bases[name.as_str()],
                float(*min),
                float(*max)
            ),
            Node::Function { name, body } => format!(
                "Node::Function({}, {})",
                keyword(name),
                body.map_or_else(|| "None".to_owned(), |body| format!("Some({body})"))
            ),
            Node::Block { open, body } => format!(
                "Node::Block(BlockKind::{}, {body})",
                if *open == '(' {
                    "Parenthesis"
                } else {
                    "SquareBracket"
                }
            ),
            Node::Sequence(children) => format!("Node::Sequence(&{children:?})"),
            Node::AllOf(children) => format!("Node::AllOf(&{children:?})"),
            Node::AnyOf(children) => format!("Node::AnyOf(&{children:?})"),
            Node::OneOf(children) => format!("Node::OneOf(&{children:?})"),
            Node::Repeat {
                node,
                min,
                max,
                comma,
            } => format!(
                "Node::Repeat {{ node: {node}, min: {min}, max: {}, comma: {comma} }}",
                if *max == UNBOUNDED {
                    "UNBOUNDED".to_owned()
                } else {
                    max.to_string()
                }
            ),
            Node::NonEmpty(node) => format!("Node::NonEmpty({node})"),
            Node::Reference { label: l, target } => {
                format!("Node::Reference({}, {target})", label(l))
            }
        };
        writeln!(out, "    {text},").unwrap();
    }
    out.push_str("];\n\n");

    writeln!(
        out,
        "pub(crate) static PROPERTIES: [PropertyData; {}] = [",
        grammar.properties.len()
    )
    .unwrap();
    for p in &grammar.properties {
        let initial = match &p.initial {
            Initial::Value(value) => format!("Initial::Value({value:?})"),
            Initial::Prose(_) => "Initial::Prose".to_owned(),
            Initial::Longhands(longhands) => format!(
                "Initial::Longhands(&[{}])",
                longhands
                    .iter()
                    .map(|name| property(name))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
        };
        let origin = match p.origin {
            Origin::Specification => "Origin::Specification",
            Origin::Errata => "Origin::Errata",
            Origin::Extension => "Origin::Extension",
        };
        writeln!(
            out,
            "    PropertyData {{ {TEST_ONLY} syntax: {:?}, root: {}, initial: {initial}, inherited: {}, {TEST_ONLY} groups: &{:?}, {TEST_ONLY} origin: {origin} }},",
            p.syntax,
            p.root,
            p.inherited,
            p.groups,
        )
        .unwrap();
    }
    out.push_str("];\n\n");

    writeln!(
        out,
        "pub(crate) static DESCRIPTORS: [DescriptorData; {}] = [",
        grammar.descriptors.len()
    )
    .unwrap();
    let mut sorted: Vec<_> = grammar.descriptors.iter().collect();
    sorted.sort_by_key(|d| descriptor_variant(d));
    for d in sorted {
        writeln!(
            out,
            "    DescriptorData {{ descriptor: Descriptor::{}, at_rule: {:?}, name: {:?}, {TEST_ONLY} syntax: {:?}, root: {}, initial: {:?} }},",
            descriptors[&descriptor_variant(d)],
            d.at_rule,
            d.name,
            d.syntax,
            d.root,
            d.initial,
        )
        .unwrap();
    }
    out.push_str("];\n\n");

    writeln!(
        out,
        "pub(crate) const COLOR_SYNTAX: NodeId = {};",
        grammar.color
    )
    .unwrap();
    writeln!(
        out,
        "{TEST_ONLY}\npub(crate) static SPEC_UNITS: [&str; {}] = {:?};",
        grammar.units.len(),
        grammar.units
    )
    .unwrap();
    Ok(out)
}

/// Unique Rust variant names in source order, keyed by CSS name.
fn variants<N: AsRef<str>>(
    names: impl Iterator<Item = N>,
    mangle: impl Fn(&str) -> String,
) -> Result<BTreeMap<String, String>, BuildError> {
    let mut seen = BTreeMap::new();
    let mut order = Vec::new();
    for name in names {
        let name = name.as_ref();
        let variant = mangle(name);
        if let Some(previous) = seen.insert(variant.clone(), name.to_owned()) {
            return Err(BuildError::Invalid {
                context: "identifier mangling".into(),
                message: format!("{previous} and {name} both map to {variant}"),
            });
        }
        order.push((name.to_owned(), variant));
    }
    Ok(order.into_iter().collect())
}

fn descriptor_variant(descriptor: &CompiledDescriptor) -> String {
    format!(
        "{}{}",
        camel(descriptor.at_rule.trim_start_matches('@')),
        camel(&descriptor.name)
    )
}

/// An `enum`, with `ALL` in CSS-name order and sorted `NAMES` when the engine looks names up.
fn enumeration(out: &mut String, name: &str, variants: &BTreeMap<String, String>, lookup: bool) {
    writeln!(
        out,
        "// Variant names are the specification's, which may repeat the enum name.\n#[allow(clippy::enum_variant_names)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]\npub(crate) enum {name} {{"
    )
    .unwrap();
    for variant in variants.values() {
        writeln!(out, "    {variant},").unwrap();
    }
    out.push_str("}\n\n");
    if !lookup {
        return;
    }
    writeln!(out, "impl {name} {{").unwrap();
    writeln!(
        out,
        "    pub(crate) const ALL: [Self; {}] = [{}];",
        variants.len(),
        variants
            .values()
            .map(|v| format!("Self::{v}"))
            .collect::<Vec<_>>()
            .join(", ")
    )
    .unwrap();
    writeln!(
        out,
        "    pub(crate) const NAMES: [&'static str; {}] = {:?};",
        variants.len(),
        variants.keys().collect::<Vec<_>>()
    )
    .unwrap();
    out.push_str("}\n\n");
}

fn float(value: f64) -> String {
    if value == f64::INFINITY {
        "f32::INFINITY".into()
    } else if value == f64::NEG_INFINITY {
        "f32::NEG_INFINITY".into()
    } else {
        format!("{:?}", value as f32)
    }
}

fn production(name: &str) -> String {
    match name.strip_suffix(FUNCTION_SUFFIX) {
        Some(function) => format!("{}{FUNCTION_VARIANT_SUFFIX}", camel(function)),
        None => camel(name),
    }
}

/// Kebab-case CSS name to a Rust variant name.
fn camel(name: &str) -> String {
    let mut out = String::new();
    if name.starts_with('-') {
        out.push_str(VENDOR_PREFIX);
    }
    for part in name.split(['-', '_']).filter(|part| !part.is_empty()) {
        let mut chars = part.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.extend(chars.map(|c| c.to_ascii_lowercase()));
        }
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert_str(0, DIGIT_PREFIX);
    }
    if RESERVED.contains(&out.as_str()) {
        out.push_str(RESERVED_SUFFIX);
    }
    out
}
