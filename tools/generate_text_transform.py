"""Generate CSS Text 3 width/kana maps from pinned primary-source files."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
UNICODE_SHA256 = '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c'
CSS_SHA256 = '17c26f1b41455947f106dac81736944b12da328ee4892c7c5b601f5b65ced55a'
DECOMPOSITION_FIELD = 5
WIDTH_MAPPINGS = 226
KANA_MAPPINGS = 58


def read_source(path, expected):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected:
        raise ValueError(f'Unexpected source revision: {path}')
    return data.decode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('unicode_data', type=Path)
    parser.add_argument('css_text', type=Path)
    args = parser.parse_args()
    unicode_data = read_source(args.unicode_data, UNICODE_SHA256)
    css = read_source(args.css_text, CSS_SHA256)
    width = {}
    records = []
    for record in unicode_data.splitlines():
        fields = record.split(';')
        mapping = fields[DECOMPOSITION_FIELD].split()
        if not mapping or mapping[0] not in ('<wide>', '<narrow>'):
            continue
        if len(mapping) != 2:
            raise ValueError(f'Expected single-scalar width mapping: {record}')
        original, decomposition = int(fields[0], 16), int(mapping[1], 16)
        source, target = (original, decomposition) if mapping[0] == '<narrow>' else (decomposition, original)
        if source in width:
            raise ValueError(f'Duplicate source scalar: {source:X}')
        width[source] = target
        records.append(record)
    appendix = css.split('id="small-kana"', 1)[1].split('</table>', 1)[0]
    codepoints = [int(value, 16) for value in re.findall(r'<td>[^<]*?U\+([0-9A-F]+)', appendix)]
    if len(codepoints) % 2:
        raise ValueError('Incomplete kana table row')
    kana = dict(zip(codepoints[::2], codepoints[1::2]))
    if len(width) != WIDTH_MAPPINGS or len(kana) != KANA_MAPPINGS:
        raise ValueError(f'Unexpected map sizes: {len(width)}, {len(kana)}')
    output = ['// Generated by tools/generate_text_transform.py; see transform-data.md.',
              '// Unicode-derived width mappings: Unicode-3.0.']
    for name, mapping in [('full_width', width), ('full_size_kana', kana)]:
        output += [f'pub(super) fn {name}(ch: char) -> char {{', '    match ch {']
        output += [f"        '\\u{{{source:x}}}' => '\\u{{{target:x}}}'," for source, target in sorted(mapping.items())]
        output += ['        _ => ch,', '    }', '}', '']
    (ROOT / 'src/document/inline/transform_maps.rs').write_text('\n'.join(output))
    fixtures = ROOT / 'src/document/tests/fixtures'
    fixtures.mkdir(exist_ok=True)
    (fixtures / 'width-decompositions.txt').write_text('\n'.join(records) + '\n')
    (fixtures / 'small-kana.txt').write_text('\n'.join(f'{source:04X};{target:04X}' for source, target in sorted(kana.items())) + '\n')


if __name__ == '__main__':
    main()
