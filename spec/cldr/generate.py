"""Extract quotation systems from the pinned CLDR core archive."""

import argparse
import hashlib
import json
from pathlib import Path
from xml.etree import ElementTree
from zipfile import ZipFile

ARCHIVE_SHA256 = "06c7c698d6fd8d67cefac15a0206b0109b00e0ef1636f86f84449fa959561f74"
DELIMITERS = ("quotationStart", "quotationEnd", "alternateQuotationStart", "alternateQuotationEnd")
INHERITANCE_MARKER = "↑↑↑"
ROOT_LOCALE = "root"


def generate(archive_path):
    archive_bytes = archive_path.read_bytes()
    if hashlib.sha256(archive_bytes).hexdigest() != ARCHIVE_SHA256:
        raise ValueError("CLDR archive does not match the pinned version 48 SHA-256")
    with ZipFile(archive_path) as archive:
        locales = {
            Path(name).stem: ElementTree.fromstring(archive.read(name))
            for name in archive.namelist()
            if name.startswith("common/main/") and name.endswith(".xml")
        }
        supplemental = ElementTree.fromstring(archive.read("common/supplemental/supplementalData.xml"))
        parents = {
            locale: entry.attrib["parent"]
            for entry in supplemental.findall("parentLocales/parentLocale")
            for locale in entry.attrib["locales"].split()
        }

        def parent(locale):
            return parents.get(locale, locale.rsplit("_", 1)[0] if "_" in locale else ROOT_LOCALE)

        def delimiters(locale):
            values = {}
            while len(values) < len(DELIMITERS):
                for key in DELIMITERS:
                    node = locales.get(locale)
                    value = node.findtext(f"delimiters/{key}") if node is not None else None
                    if value is not None and value != INHERITANCE_MARKER:
                        values.setdefault(key, value)
                if locale == ROOT_LOCALE:
                    break
                locale = parent(locale)
            return tuple(values[key] for key in DELIMITERS)

        systems = {locale: delimiters(locale) for locale in locales}

        def best(locale):
            if locale in systems:
                return systems[locale]
            parts = locale.split("_")
            if len(parts) >= 3 and len(parts[1]) == 4:
                without_script = "_".join([parts[0], *parts[2:]])
                if without_script in systems:
                    return systems[without_script]
            while "_" in locale:
                locale = parent(locale)
                if locale in systems:
                    return systems[locale]
            return systems.get(locale, systems[ROOT_LOCALE])

        likely = ElementTree.fromstring(archive.read("common/supplemental/likelySubtags.xml"))
        for entry in likely.findall("likelySubtags/likelySubtag"):
            systems.setdefault(entry.attrib["from"], best(entry.attrib["to"]))
        metadata = ElementTree.fromstring(archive.read("common/supplemental/supplementalMetadata.xml"))
        for entry in metadata.findall("metadata/alias/languageAlias"):
            systems.setdefault(entry.attrib["type"], best(entry.attrib["replacement"].split()[0]))
        licence = archive.read("LICENSE")

    unique = sorted(set(systems.values()))
    indices = {system: index for index, system in enumerate(unique)}
    literal = lambda value: json.dumps(value, ensure_ascii=False)
    output = ["// Generated by spec/cldr/generate.py from CLDR 48; Unicode-3.0.\n"]
    output.append("pub(super) const SYSTEMS: &[[[&str; 2]; 2]] = &[\n")
    for first, second, third, fourth in unique:
        output.append(f"    [[{literal(first)}, {literal(second)}], [{literal(third)}, {literal(fourth)}]],\n")
    output.append("];\npub(super) const LOCALES: &[(&str, usize)] = &[\n")
    for locale, system in sorted(systems.items(), key=lambda pair: pair[0].lower().replace("_", "-")):
        output.append(f"    ({literal(locale.lower().replace('_', '-'))}, {indices[system]}),\n")
    output.append("];\n")
    directory = Path(__file__).resolve().parent
    (directory / "quotes.rs").write_text("".join(output), encoding="utf-8")
    (directory / "LICENSE").write_bytes(licence)
    print(f"Generated {len(systems)} locale systems, {len(unique)} distinct quotation systems")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path)
    generate(parser.parse_args().archive)
