"""Extract the emoji presentation participating code points from the pinned UCD file."""

import argparse
import hashlib
from pathlib import Path

SOURCE_SHA256 = "bb3d09ef03f206012c7532dd52dc0a21c9efddba0135ea4cf0d9201b8b9bba7e"
PRESENTATION_SELECTORS = {"FE0E", "FE0F"}
VALUES_PER_LINE = 8


def generate(source_path):
    source = source_path.read_bytes()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise ValueError("emoji-variation-sequences.txt does not match the pinned Unicode 17.0.0 SHA-256")
    bases = set()
    for line in source.decode("utf-8").splitlines():
        sequence = line.split("#", 1)[0].split(";", 1)[0].split()
        if len(sequence) != 2:
            continue
        base, selector = sequence
        if selector not in PRESENTATION_SELECTORS:
            raise ValueError(f"unexpected selector in {line!r}")
        bases.add(int(base, 16))
    ordered = sorted(bases)
    output = ["// Generated by spec/emoji/generate.py from Unicode 17.0.0; Unicode-3.0.\n"]
    output.append("pub(super) const VARIATION_BASES: &[u32] = &[\n")
    for start in range(0, len(ordered), VALUES_PER_LINE):
        values = ", ".join(f"0x{value:04X}" for value in ordered[start : start + VALUES_PER_LINE])
        output.append(f"    {values},\n")
    output.append("];\n")
    (Path(__file__).resolve().parent / "variation_bases.rs").write_text("".join(output), encoding="utf-8")
    print(f"Generated {len(ordered)} emoji presentation participating code points")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    generate(parser.parse_args().source)
