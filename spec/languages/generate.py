"""Extract RFC 5646 canonicalization data from the pinned IANA registry."""

import argparse
import hashlib
import json
from pathlib import Path

REGISTRY_SHA256 = "755fad43283be7b41ebe3c89ad054b6eaf928f404f9c0edb74799e0eab74beb1"
TYPES = ("grandfathered", "redundant", "language", "script", "region", "variant")


def generate(path):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != REGISTRY_SHA256:
        raise ValueError("IANA registry does not match the pinned 2026-09-17 SHA-256")
    aliases = {kind: {} for kind in TYPES}
    extlangs = {}
    for record in data.decode("utf-8").split("%%")[1:]:
        fields = {}
        for line in record.splitlines():
            if line and not line.startswith(" "):
                key, value = line.split(": ", 1)
                fields.setdefault(key, []).append(value)
        kind = fields["Type"][0]
        if kind in aliases and "Preferred-Value" in fields:
            key = fields.get("Subtag", fields.get("Tag"))[0].lower()
            aliases[kind][key] = fields["Preferred-Value"][0].lower()
        if kind == "extlang":
            if len(fields["Prefix"]) != 1:
                raise ValueError("multiple extlang prefixes require an explicit canonicalization policy")
            extlangs[fields["Subtag"][0].lower()] = fields["Prefix"][0].lower()
    aliases["tag"] = aliases.pop("grandfathered") | aliases.pop("redundant")
    aliases["extlang"] = extlangs
    output = ["// Generated by spec/languages/generate.py from IANA 2026-09-17.\n"]
    for kind, values in aliases.items():
        output.append(f"pub(super) const {kind.upper()}: &[(&str, &str)] = &[\n")
        output.extend(f"    ({json.dumps(key)}, {json.dumps(value)}),\n" for key, value in sorted(values.items()))
        output.append("];\n")
    Path(__file__).with_name("aliases.rs").write_text("".join(output), encoding="utf-8")
    print({kind: len(values) for kind, values in aliases.items()})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("registry", type=Path)
    generate(parser.parse_args().registry)
